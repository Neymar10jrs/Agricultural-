import fs from 'fs';
import { geoMercator } from 'd3-geo';

const geojson = JSON.parse(fs.readFileSync('../india_simplified2.geojson', 'utf-8'));

// Rename legacy/old names to current official names
const nameFixes = {
  Orissa: 'Odisha',
  Uttaranchal: 'Uttarakhand',
  Puducherry: 'Puducherry',
};

const WIDTH = 700;
const HEIGHT = 780;

// India's real extent, padded generously. Any ring containing a point
// outside this box is a data artifact (e.g. a degenerate repair ring left
// behind by mapshaper's intersection-cleanup) and gets dropped entirely.
const SANE_LON = [55, 110];
const SANE_LAT = [-10, 45];
function isSaneRing(ring) {
  return ring.every(
    ([lon, lat]) => lon >= SANE_LON[0] && lon <= SANE_LON[1] && lat >= SANE_LAT[0] && lat <= SANE_LAT[1]
  );
}
function sanitizeGeometry(geometry) {
  if (geometry.type === 'Polygon') {
    const rings = geometry.coordinates.filter(isSaneRing);
    return { ...geometry, coordinates: rings };
  }
  if (geometry.type === 'MultiPolygon') {
    const polygons = geometry.coordinates
      .map((rings) => rings.filter(isSaneRing))
      .filter((rings) => rings.length > 0);
    return { ...geometry, coordinates: polygons };
  }
  return geometry;
}
for (const feature of geojson.features) {
  feature.geometry = sanitizeGeometry(feature.geometry);
}

const PADDING = 24;

// fitSize() internally relies on the same bounds-computation machinery that's
// buggy in this d3-geo build, so it silently produces a tiny, mis-scaled
// projection. Compute scale/translate manually instead, using a raw
// scale-1 projection to measure India's real projected extent.
const probe = geoMercator().scale(1).translate([0, 0]);
let minX = Infinity,
  maxX = -Infinity,
  minY = Infinity,
  maxY = -Infinity;
for (const feature of geojson.features) {
  const points = flattenCoords(feature.geometry);
  for (const coord of points) {
    const p = probe(coord);
    if (!p || !Number.isFinite(p[0]) || !Number.isFinite(p[1])) continue;
    if (p[0] < minX) minX = p[0];
    if (p[0] > maxX) maxX = p[0];
    if (p[1] < minY) minY = p[1];
    if (p[1] > maxY) maxY = p[1];
  }
}

function flattenCoords(geometry) {
  const coords = geometry.coordinates;
  if (geometry.type === 'Polygon') return coords.flat(1);
  if (geometry.type === 'MultiPolygon') return coords.flat(2);
  return [];
}

const scaleX = (WIDTH - PADDING * 2) / (maxX - minX);
const scaleY = (HEIGHT - PADDING * 2) / (maxY - minY);
const scale = Math.min(scaleX, scaleY);
const midX = (minX + maxX) / 2;
const midY = (minY + maxY) / 2;

const projection = geoMercator()
  .scale(scale)
  .translate([WIDTH / 2 - midX * scale, HEIGHT / 2 - midY * scale]);

function buildPathD(geometry) {
  const polygons =
    geometry.type === 'Polygon' ? [geometry.coordinates] : geometry.type === 'MultiPolygon' ? geometry.coordinates : [];
  let d = '';
  for (const rings of polygons) {
    for (const ring of rings) {
      if (ring.length === 0) continue;
      const projected = ring.map((coord) => projection(coord)).filter((p) => p && Number.isFinite(p[0]) && Number.isFinite(p[1]));
      if (projected.length < 3) continue;
      d += `M${projected[0][0].toFixed(2)},${projected[0][1].toFixed(2)}`;
      for (let i = 1; i < projected.length; i++) {
        d += `L${projected[i][0].toFixed(2)},${projected[i][1].toFixed(2)}`;
      }
      d += 'Z';
    }
  }
  return d;
}

const features = geojson.features.map((f) => {
  const rawName = f.properties.NAME_1;
  const name = nameFixes[rawName] || rawName;
  const d = buildPathD(f.geometry);

  const points = flattenCoords(f.geometry)
    .map((coord) => projection(coord))
    .filter((p) => p && Number.isFinite(p[0]) && Number.isFinite(p[1]));
  const centroid =
    points.length > 0
      ? [
          Math.round((points.reduce((sum, p) => sum + p[0], 0) / points.length) * 100) / 100,
          Math.round((points.reduce((sum, p) => sum + p[1], 0) / points.length) * 100) / 100,
        ]
      : [WIDTH / 2, HEIGHT / 2];

  return { name, d, centroid };
});

// Sort alphabetically for stable diffs
features.sort((a, b) => a.name.localeCompare(b.name));

const out = `// AUTO-GENERATED by scripts/generate-india-map.mjs — do not hand-edit.
// Source: geohacker/india state boundaries, simplified with mapshaper (~1%),
// projected with d3-geo (Mercator, fit to ${WIDTH}x${HEIGHT} viewBox).
// Regenerate if boundary accuracy needs improving.

export interface IndiaStateShape {
  name: string;
  d: string;
  centroid: [number, number];
}

export const INDIA_MAP_VIEWBOX = '0 0 ${WIDTH} ${HEIGHT}';

export const INDIA_STATE_SHAPES: IndiaStateShape[] = ${JSON.stringify(
  features.map((f) => ({ name: f.name, d: f.d, centroid: f.centroid })),
  null,
  2
)};
`;

fs.writeFileSync('../indiaStateShapes.generated.ts', out);
console.log('Wrote', features.length, 'state shapes');
console.log('Output size:', fs.statSync('../indiaStateShapes.generated.ts').size, 'bytes');
